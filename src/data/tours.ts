function meal(
  time: string,
  title: string,
  restaurant: { name: string; address: string; kosherLevel: 'glatt' | 'supervised'; kosherAuthority: string; cuisine: string; priceRange: string },
  extra?: Partial<ItineraryStop>
): ItineraryStop {
  return {
    id: `${time}-${restaurant.name}`,
    time,
    title,
    location: restaurant.address,
    type: 'food',
    kosherLevel: restaurant.kosherLevel,
    kosherAuthority: restaurant.kosherAuthority,
    priceRange: restaurant.priceRange,
    tag: restaurant.cuisine,
    ...extra,
  };
}

